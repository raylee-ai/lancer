"""Markdown and HTML reports. Numbers come only from the summary dict."""

from __future__ import annotations

import html
from pathlib import Path

from lancer_eval.types import FAILURE_BUCKETS

NOT_RUN = "未运行"


def _cell(value: object) -> str:
    if value is None:
        return NOT_RUN
    if isinstance(value, float):
        return f"{value:.4g}"
    if isinstance(value, bool):
        return "yes" if value else "no"
    return str(value)


def _html_cell(value: object) -> str:
    return html.escape(_cell(value))


def _bucket(value: object) -> str:
    """A missing bucket means attribution found no failure, not that the run was skipped."""

    if value is None:
        return "—"
    return _cell(value)


def _rate(value: object) -> str:
    if value is None:
        return NOT_RUN
    if isinstance(value, (int, float)):
        return f"{value * 100:.1f}%"
    return _cell(value)


def render_markdown(summary: dict) -> str:
    lines = [
        "# Coding agent evaluation",
        "",
        summary.get("note") or "Generated by a run. Not a published benchmark score.",
        "",
        f"- Dataset: {summary.get('dataset') or 'custom task set'}",
        f"- Split: {summary.get('split') or NOT_RUN}",
        f"- Requested grade: {summary.get('requested_grade')}",
        f"- Grade mode: {summary.get('grade_mode')}",
        f"- Fallback: {summary.get('grade_fallback_reason') or NOT_RUN}",
        f"- Run id: {summary.get('run_id')}",
        "",
        "Resolve rate counts only instances whose `resolved` field is true or false.",
        f"A cell shows {NOT_RUN} when that measurement was not taken.",
        "That is not a score of zero.",
        "",
        "Failure buckets are heuristics over the agent log, the patch, and the grade.",
        "An LLM judge, when present, is labeled `llm_judge` and does not replace the",
        "heuristic unless the run was started with judge override.",
        "",
        "## Adapters",
        "",
        "| Adapter | Instances | Official graded | Resolved | Resolve rate | Patch applies | Patch-applies rate | Mean wall (s) | Median wall (s) | Input tokens | Output tokens | Cost (USD) | Mean tool calls | Mean turns |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for adapter in summary.get("adapters") or []:
        lines.append(
            "| "
            + " | ".join(
                [
                    _cell(adapter.get("adapter")),
                    _cell(adapter.get("instances")),
                    _cell(adapter.get("official_graded")),
                    _cell(adapter.get("resolved")),
                    _rate(adapter.get("resolve_rate")),
                    _cell(adapter.get("patch_applies")),
                    _rate(adapter.get("patch_applies_rate")),
                    _cell(adapter.get("mean_wall_time_seconds")),
                    _cell(adapter.get("median_wall_time_seconds")),
                    _cell(adapter.get("input_tokens")),
                    _cell(adapter.get("output_tokens")),
                    _cell(adapter.get("cost_usd")),
                    _cell(adapter.get("mean_tool_calls")),
                    _cell(adapter.get("mean_turns")),
                ]
            )
            + " |"
        )
    if not summary.get("adapters"):
        lines.append("未运行。没有适配器执行实例。")
    lines.extend(["", "## Failure buckets", "", "| Adapter | " + " | ".join(FAILURE_BUCKETS) + " |", "| --- | " + " | ".join(["---:"] * len(FAILURE_BUCKETS)) + " |"])
    for adapter in summary.get("adapters") or []:
        buckets = adapter.get("failure_buckets") or {}
        counts = " | ".join(str(buckets.get(name, 0)) for name in FAILURE_BUCKETS)
        lines.append(f"| {adapter.get('adapter')} | {counts} |")
    lines.extend(
        [
            "",
            "## Instances",
            "",
            "| Adapter | Instance | Resolved | Patch applies | Grade | Wall (s) | Tokens in/out | Cost | Tools | Turns | Failure bucket | Bucket source | Judge |",
            "| --- | --- | --- | --- | --- | ---: | --- | ---: | ---: | ---: | --- | --- | --- |",
        ]
    )
    for record in summary.get("instances") or []:
        tokens = NOT_RUN
        if record.get("input_tokens") is not None or record.get("output_tokens") is not None:
            tokens = f"{_cell(record.get('input_tokens'))}/{_cell(record.get('output_tokens'))}"
        judge = (record.get("llm_judge") or {}).get("bucket") if isinstance(record.get("llm_judge"), dict) else None
        lines.append(
            "| "
            + " | ".join(
                [
                    _cell(record.get("adapter")),
                    _cell(record.get("instance_id")),
                    _cell(record.get("resolved")),
                    _cell(record.get("patch_applies")),
                    _cell(record.get("grade_mode")),
                    _cell(record.get("wall_time_seconds")),
                    tokens,
                    _cell(record.get("cost_usd")),
                    _cell(record.get("tool_calls")),
                    _cell(record.get("turns")),
                    _bucket(record.get("failure_bucket")),
                    _cell(record.get("failure_source")),
                    _cell(judge),
                ]
            )
            + " |"
        )
    skipped = summary.get("skipped_adapters") or []
    lines.extend(["", "## Skipped adapters", "", "以下适配器未运行。", ""])
    if not skipped:
        lines.append("None.")
    else:
        lines.append("| Adapter | Reason | Detail |")
        lines.append("| --- | --- | --- |")
        for item in skipped:
            detail = (item.get("detail") or "").replace("\n", " ").replace("|", "/")
            lines.append(f"| {item.get('adapter')} | {item.get('reason')} | {detail} |")
    lines.extend(
        [
            "",
            "## Notes",
            "",
            "- Wall time is the agent call only. Clone and grading time are not included.",
            f"- {NOT_RUN} means that measurement was not taken. It is not a score of zero.",
            "- A dash in the failure column means attribution found no failure bucket.",
            "- Token and cost cells are 未运行 when the adapter did not report them.",
            "- Cost is the adapter-reported cost, or a token price supplied for that run.",
            "- `context_retrieval_miss` compares edited files with the official gold patch file list.",
            "  The gold patch is not shown to the agent.",
            "",
        ]
    )
    return "\n".join(lines)


def render_html(summary: dict) -> str:
    markdown = render_markdown(summary)
    # A single preformatted report keeps the HTML optional and free of external assets.
    body = html.escape(markdown)
    title = html.escape(f"Coding agent evaluation {summary.get('run_id') or ''}")
    return (
        "<!DOCTYPE html>\n"
        "<html lang=\"en\">\n"
        "<head>\n"
        "<meta charset=\"utf-8\">\n"
        f"<title>{title}</title>\n"
        "<style>body{font:14px/1.45 ui-sans-serif,sans-serif;margin:2rem;max-width:1100px}"
        "pre{white-space:pre-wrap}</style>\n"
        "</head>\n"
        "<body>\n"
        f"<pre>{body}</pre>\n"
        "</body>\n"
        "</html>\n"
    )


def write_reports(directory: Path, summary: dict) -> tuple[Path, Path]:
    directory.mkdir(parents=True, exist_ok=True)
    markdown_path = directory / "report.md"
    html_path = directory / "report.html"
    markdown_path.write_text(render_markdown(summary), encoding="utf-8")
    html_path.write_text(render_html(summary), encoding="utf-8")
    return markdown_path, html_path
